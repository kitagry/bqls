//go:build ignore

// This program is run via "go generate" to generate builtin functions from the
// GoogleSQL function reference vendored in googlesql_docs/ (no network access).

package main

import (
	"bytes"
	"fmt"
	"go/format"
	"log"
	"os"
	"path/filepath"
	"strings"
	"text/template"

	"github.com/kitagry/bqls/langserver/internal/function/internal/docparse"
)

const docsDir = "googlesql_docs"

// docFiles lists the vendored pages that are in scope: function references
// that BigQuery also documents, under the same page name. Operators,
// differential privacy, graph, protocol buffer, HLL, range and time series
// functions are intentionally left out because BigQuery does not support them.
var docFiles = []string{
	"aggregate_functions",
	"approximate_aggregate_functions",
	"array_functions",
	"bit_functions",
	"conversion_functions",
	"date_functions",
	"datetime_functions",
	"debugging_functions",
	"geography_functions",
	"hash_functions",
	"interval_functions",
	"json_functions",
	"mathematical_functions",
	"navigation_functions",
	"net_functions",
	"numbering_functions",
	"security_functions",
	"statistical_aggregate_functions",
	"string_functions",
	"time_functions",
	"timestamp_functions",
}

func main() {
	var functions []docparse.Function
	seen := map[string]string{}
	for _, name := range docFiles {
		src, err := os.ReadFile(filepath.Join(docsDir, name+".md"))
		if err != nil {
			log.Fatal(err)
		}
		fs, err := docparse.Parse(src, docparse.BigQueryDocsBase+name)
		if err != nil {
			log.Fatalf("%s: %v", name, err)
		}
		if len(fs) == 0 {
			log.Fatalf("%s: no functions found", name)
		}
		for _, f := range fs {
			if prev, ok := seen[f.Name]; ok {
				log.Printf("skip duplicate %s in %s (already in %s)", f.Name, name, prev)
				continue
			}
			seen[f.Name] = name
			functions = append(functions, f)
		}
	}
	if len(functions) == 0 {
		log.Fatal("no functions found; refusing to overwrite builtin_function.go")
	}

	generate(functions)
}

func generate(functions []docparse.Function) {
	funcMap := template.FuncMap{
		"escape": func(s string) string {
			out := strings.ReplaceAll(s, "\\", "\\\\")
			out = strings.ReplaceAll(out, "\n", "\\n")
			out = strings.ReplaceAll(out, "\"", "\\\"")
			return out
		},
	}

	tmpl, err := template.New("gen").Funcs(funcMap).Parse(templateCode)
	if err != nil {
		log.Fatal(err)
	}

	var out bytes.Buffer
	err = tmpl.Execute(&out, map[string]any{
		"Functions": functions,
	})
	if err != nil {
		log.Fatal("template Execute:", err)
	}

	formatted, err := format.Source(out.Bytes())
	if err != nil {
		fmt.Println(out.String())
		log.Fatal("format:", err)
	}

	if err := os.WriteFile("builtin_function.go", formatted, 0644); err != nil {
		log.Fatal("write file:", err)
	}
}

const templateCode = `// Code generated by gen_builtin_function.go, DO NOT EDIT.
package function

var BuiltInFunctions = []BuiltInFunction{
		{{range .Functions}}{
			Name:            "{{.Name}}",
			Method:          "{{.Method | escape}}",
			Description: "{{.Description | escape}}",
			ExampleSQLs:     []string{
				{{range .ExampleSQLs}}"{{. | escape}}",
			{{end}}},
			URL: "{{.URL}}",
		},
{{end}}}
`
